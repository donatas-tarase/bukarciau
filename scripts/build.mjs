import {readFile, writeFile, mkdir, rm, cp} from 'node:fs/promises';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';
import {parseContent} from '../shared/content.mjs';
import {renderPage, renderRobots, renderSitemap} from '../shared/render.mjs';

const content = parseContent(JSON.parse(await readFile('content.json', 'utf8')));
const version = async path => `${path}?v=${createHash('sha256').update(await readFile('.' + path)).digest('hex').slice(0,12)}`;
const assets = {styles:await version('/styles.css'), script:await version('/app.js')};
await rm('dist', {recursive:true, force:true});
await mkdir('dist/assets', {recursive:true});
for (const file of ['styles.css','app.js','_headers','_redirects']) await cp(file,join('dist',file));
for (const file of ['logo.svg','favicon.svg','logo-original.jpeg','montserrat-latin.woff2','montserrat-latin-ext.woff2','FONT-LICENSE.txt']) await cp(join('assets',file),join('dist/assets',file));
const paths = ['/', '/apie-mus/', '/kontaktai/', '/stovyklos/stovykla-01/', '/404.html'];
for (const path of paths) {
  const rendered = renderPage(content,path,{assets});
  if (!rendered?.html) throw new Error(`Nepavyko sugeneruoti ${path}`);
  const file = path === '/' ? 'index.html' : path.endsWith('/') ? path.slice(1) + 'index.html' : path.slice(1);
  const directory = file.includes('/') ? file.slice(0,file.lastIndexOf('/')) : '';
  await mkdir(join('dist',directory),{recursive:true});
  await writeFile(join('dist',file),rendered.html);
}
await writeFile('dist/robots.txt',renderRobots(content));
const sitemap = renderSitemap(content);
if (sitemap) await writeFile('dist/sitemap.xml',sitemap);
await mkdir('dist/admin',{recursive:true});
for (const file of ['index.html','admin.css','admin.js','visual.css']) await cp(join('admin',file),join('dist/admin',file));
await cp('shared/content.mjs','dist/admin/schema.mjs');
await writeFile('dist/admin/render.mjs',(await readFile('shared/render.mjs','utf8')).replace("from './content.mjs'","from './schema.mjs'"));
await mkdir('server',{recursive:true});
await writeFile('server/generated.mjs',`// Generated by build. No credentials belong here.\nexport const initialContent = ${JSON.stringify(content)};\nexport const assets = ${JSON.stringify(assets)};\n`);
await build({entryPoints:['server/worker.mjs'],outfile:'dist/_worker.js',bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,legalComments:'none'});
await writeFile('dist/_routes.json',JSON.stringify({version:1,include:['/*'],exclude:[]},null,2)+'\n');
console.log(`Sukurti ${paths.length} puslapiai ir apsaugotas turinio redaktorius kataloge dist/.`);
